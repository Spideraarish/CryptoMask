import os
from kms_core import KMS

class AccessController:
    """
    Simulates an OS-level File System Interceptor.
    Requires a valid HMAC generated by the KMS to authorize file modifications.
    """
    def __init__(self, watch_dir="Dummy_Files"):
        self.watch_dir = watch_dir
        self.kms = KMS()
        
        if not os.path.exists(self.watch_dir):
            os.makedirs(self.watch_dir)

    def request_write(self, filepath: str, data: bytes, operation: str, timestamp: str, provided_mac: str) -> dict:
        """
        Intercepts the write request.
        Evaluates the Cryptographic Access-Control policy and returns a detailed trace.
        """
        filename = os.path.basename(filepath)
        
        # Core Defense Mechanism: Generate expected MAC using master key
        expected_mac = self.kms.generate_mac(filename, operation, timestamp)
        is_valid = self.kms.verify_mac(filename, operation, timestamp, provided_mac)
        
        response = {
            "file": filename,
            "operation": operation,
            "timestamp": timestamp,
            "expected_mac": expected_mac,
            "provided_mac": provided_mac,
            "is_valid": is_valid
        }
        
        if is_valid:
            target_path = os.path.join(self.watch_dir, filename)
            with open(target_path, "wb") as f:
                f.write(data)
            response["message"] = "Cryptographic Match Confirmed. Allowing File Write."
            response["status"] = "SUCCESS"
        else:
            response["message"] = "Cryptographic Mismatch! RANSOMWARE BLOCKED. Deleting payload."
            response["status"] = "BLOCKED"
            
        return response
